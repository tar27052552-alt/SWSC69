export function narrativeBlocks(subjectId, topicIndex) {
  const [heading, ...paragraphs] = lessonNarratives[subjectId]?.[topicIndex] || [];
  if (!heading || paragraphs.length < 2) throw new Error(`Missing lesson copy: ${subjectId} topic ${topicIndex + 1}`);
  return [
    { type: 'heading', text: heading, editorialSource: 'lesson-narrative-v1' },
    ...paragraphs.map(text => ({ type: 'paragraph', text, editorialSource: 'lesson-narrative-v1' })),
  ];
}

